const key = (text: string) => tokens(normalizeFrench(text)).join(' ');

// First entry wins, so "desserts" and "dessert" (same key) keep the plural German name.
const LOOKUP = new Map<string, string>();
for (const [fr, de] of SECTION_NAMES) if (!LOOKUP.has(key(fr))) LOOKUP.set(key(fr), de);

/** Number of distinct French headers known (for tests). */
export const SECTION_NAME_COUNT = LOOKUP.size;

/** German name of a French menu section, or null if unknown. "nos …" and "… maison" fall back to the core term. */
export function germanSection(section: string): string | null {
  const k = key(section);
  if (!k) return null;
  const exact = LOOKUP.get(k);
  if (exact) return exact;
  const core = k.replace(/^(nos|notre|no) /, '');
  return LOOKUP.get(core) ?? null;
}

/** "Entrées · Vorspeisen"; just the French title when unknown or identical. */
export function sectionTitle(section: string): string {
  const de = germanSection(section);
  if (!de || normalizeFrench(de) === normalizeFrench(section)) return section;
  return `${section} · ${de}`;
}
